import { readFile, writeFile } from "node:fs/promises";

// Export the approved ASCII Motion study as compact, colored text rows.
const source = JSON.parse(
  await readFile(new URL("../artifacts/thinker-apple/animation.json", import.meta.url), "utf8"),
);
const colors = ["#e7e3d9", "#98aa8f", "#e7a07b"];
const frames = source.animation.frames.map(({ duration, data }) => ({
  duration,
  layers: colors.map((color) => {
    const rows = new Map();
    for (const [position, cell] of Object.entries(data)) {
      if (cell.color !== color) continue;
      const [x, y] = position.split(",").map(Number);
      if (!rows.has(y)) rows.set(y, new Map());
      rows.get(y).set(x, cell.char);
    }
    return [...rows].sort(([a], [b]) => a - b).map(([y, cells]) => {
      const left = Math.min(...cells.keys());
      const right = Math.max(...cells.keys());
      const text = Array.from({ length: right - left + 1 }, (_, i) => cells.get(left + i) ?? " ").join("");
      return [left, y, text];
    });
  }),
}));

// Check the compact export against every authored character and its color.
frames.forEach((frame, i) => {
  const cells = {};
  frame.layers.forEach((rows, layer) => rows.forEach(([left, y, text]) => {
    [...text].forEach((char, offset) => {
      if (char !== " ") cells[`${left + offset},${y}`] = { char, color: colors[layer] };
    });
  }));
  const original = source.animation.frames[i].data;
  if (Object.keys(cells).length !== Object.keys(original).length ||
      Object.entries(cells).some(([key, cell]) => cell.char !== original[key]?.char || cell.color !== original[key]?.color)) {
    throw new Error(`Frame ${i} differs from the approved artwork`);
  }
});

const output = JSON.stringify({ width: source.canvas.width, height: source.canvas.height, frames });
await writeFile(new URL("../public/animations/thinker-apple.json", import.meta.url), output + "\n");
await writeFile(new URL("../app/components/thinker-still.ts", import.meta.url),
  "// Generated by scripts/export-thinker-animation.mjs.\nexport const thinkerStill = " +
  JSON.stringify(frames[0].layers) + " as const;\n");
console.log(`Exported ${frames.length} verified frames (${Math.round(output.length / 1024)} KB).`);
