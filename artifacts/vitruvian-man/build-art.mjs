function inside(x,y,poly) { let hit=false;for(let i=0,j=poly.length-1;i<poly.length;j=i++){const[a,b]=poly[i],[c,d]=poly[j];if((b>y)!=(d>y)&&x<(c-a)*(y-b)/(d-b)+a)hit=!hit;}return hit;}
const ink = Buffer.alloc(width*height);
for(let y=380;y<1340;y++)for(let x=190;x<1150;x++)if(polygons.some(p=>inside(x,y,p))){let delta=local[y*width+x]-gray[y*width+x];ink[y*width+x]=Math.max(0,Math.min(255,(delta-7)*6));}
const geometry = Buffer.from(`<svg width="1344" height="1827"><g fill="none" stroke="white" stroke-width="2.1"><circle cx="672" cy="763" r="575"/><path d="M195 392H1146V1331H195Z"/></g></svg>`);
const crop={left:86,top:177,width:1176,height:1170};
const composed = await sharp(ink,{raw:{width,height,channels:1}}).composite([{input:geometry}]).png().toBuffer();
const art = await sharp(composed).extract(crop).greyscale().png().toBuffer();
const columns = 144;
const rows = 72;
const pixels = await sharp(art).resize(columns, rows, {fit: 'fill'})
  .removeAlpha().greyscale().raw().toBuffer();
const ramp = ' .:-=+*#%@';
const lines = [];
for (let y = 0; y < rows; y++) {
  let line = '';
  for (let x = 0; x < columns; x++) {
    const value = pixels[y * columns + x];
    line += ramp[Math.floor(Math.sqrt(value / 255) * (ramp.length - 1))];
  }
  lines.push(line.trimEnd());
}
await writeFile(resolve(directory, 'vitruvian.txt'), lines.join('\n') + '\n');
await writeFile(resolve(site, 'app/thoughts/renaissance/vitruvian-data.ts'),
  '// Generated by artifacts/vitruvian-man/build-art.mjs.\n' +
  'export const vitruvianLines = ' + JSON.stringify(lines, null, 2) + ' as const;\n');
console.log(`Saved Vitruvian Man ASCII: ${columns} columns, ${rows} rows.`);
